/* ---------------------------------------------------------------- PNG */

/* eslint-disable no-bitwise -- CRC-32 for PNG chunks */
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(bytes) {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
/* eslint-enable no-bitwise */

function chunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length, 0);
  head.write(type, 4, 'ascii');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0);
  return Buffer.concat([head, data, crc]);
}

/**
 * Encodes an 8-bit greyscale image as PNG
 *
 * @param {Uint8Array} pixels Row-major pixels
 * @param {Number} size Width and height
 * @returns {Buffer} PNG file
 */
function greyPNG(pixels, size) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 0; // greyscale
  const raw = Buffer.alloc((size + 1) * size);
  for (let y = 0; y < size; y++) {
    raw[y * (size + 1)] = 0; // no filter
    Buffer.from(pixels.buffer, y * size, size).copy(raw, y * (size + 1) + 1);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/* ---------------------------------------------------------------- XML */

const escape = (value) => String(value)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

/**
 * Serialises an element: el(name, attributes, ...children), children are elements or arrays
 *
 * @returns {Function} Writer taking the indentation depth
 */
function el(name, attributes = {}, ...children) {
  return (depth = 0) => {
    const pad = '  '.repeat(depth);
    const attrs = Object.entries(attributes)
      .filter(([, v]) => v !== undefined)
      .map(([k, v]) => ` ${k}="${escape(v)}"`).join('');
    const kids = children.flat(Infinity).filter(Boolean);
    if (!kids.length) return `${pad}<${name}${attrs}/>`;
    return `${pad}<${name}${attrs}>\n${kids.map((k) => k(depth + 1)).join('\n')}\n${pad}</${name}>`;
  };
}

const num = (v) => v.toFixed(6);

/** Position matrix with a translation in meters (rotation free) */
const at = (x = 0, y = 0, z = 0) => `{1,0,0,${num(x)}}{0,1,0,${num(y)}}{0,0,1,${num(z)}}{0,0,0,1}`;

/** sRGB hex to the CIE xyY string GDTF uses for colours */
function xyY(hex) {
  const lin = [0, 2, 4].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  const X = 0.4124 * lin[0] + 0.3576 * lin[1] + 0.1805 * lin[2];
  const Y = 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
  const Z = 0.0193 * lin[0] + 0.1192 * lin[1] + 0.9505 * lin[2];
  const sum = X + Y + Z;
  return `${num(X / sum)},${num(Y / sum)},${num(Y * 100)}`;
}

