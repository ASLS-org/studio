function attributeDefinitions(names) {
  const used = [...new Set(names)];
  const features = {};
  used.forEach((n) => {
    const [group, feature] = ATTRIBUTES[n][1].split('.');
    (features[group] = features[group] || new Set()).add(feature);
  });
  return el(
    'AttributeDefinitions',
    {},
    el('ActivationGroups'),
    el('FeatureGroups', {}, Object.entries(features).map(([group, set]) => el(
      'FeatureGroup',
      { Name: group, Pretty: group },
      [...set].map((f) => el('Feature', { Name: f })),
    ))),
    el('Attributes', {}, used.map((n) => el('Attribute', {
      Name: n,
      Pretty: ATTRIBUTES[n][0],
      Feature: ATTRIBUTES[n][1],
      MainAttribute: MAIN_ATTRIBUTES[n],
      PhysicalUnit: ATTRIBUTES[n][2],
    }))),
  );
}

/* ---------------------------------------------------------------- DMX channels */

/**
 * One channel function: [name, attribute, dmxFrom, physicalFrom, physicalTo, extra, sets]
 */
function fn(name, attribute, from, physFrom, physTo, extra = {}, sets = []) {
  return {
    name, attribute, from, physFrom, physTo, extra, sets,
  };
}

/**
 * DMX channel description
 *
 * @param {String} geometry Geometry the channel drives
 * @param {Array<Number>} offset Coarse (and fine) offsets, 1-based, relative to the break
 * @param {Array<Object>} functions Channel functions (fn), the first one's attribute names it
 * @param {Number} [def=0] Default DMX value (in the channel's resolution)
 */
function channel(geometry, offset, functions, def = 0) {
  return {
    geometry, offset, functions, def,
  };
}

function channelXML(ch) {
  const bytes = ch.offset.length;
  const [{ attribute }] = ch.functions;
  const first = `${ch.geometry}_${attribute}.${attribute}.${ch.functions[0].name}`;
  return el(
    'DMXChannel',
    {
      DMXBreak: 1,
      Offset: ch.offset.join(','),
      InitialFunction: first,
      Highlight: 'None',
      Geometry: ch.geometry,
    },
    el(
      'LogicalChannel',
      {
        Attribute: attribute, Snap: 'No', Master: 'None', MibFade: num(0), DMXChangeTimeLimit: num(0),
      },
      ch.functions.map((f) => el(
        'ChannelFunction',
        {
          Name: f.name,
          Attribute: f.attribute,
          OriginalAttribute: '',
          DMXFrom: `${f.from}/${bytes}`,
          Default: `${f === ch.functions[0] ? ch.def : f.from}/${bytes}`,
          PhysicalFrom: num(f.physFrom),
          PhysicalTo: num(f.physTo),
          RealFade: num(0),
          RealAcceleration: num(0),
          ...f.extra,
        },
        f.sets.map((s) => el('ChannelSet', {
          Name: s.name, DMXFrom: `${s.from}/${bytes}`, WheelSlotIndex: s.slot,
        })),
      )),
    ),
  );
}

/** A linear channel from 0 to full */
const linear = (geometry, offset, attribute, physFrom, physTo, def = 0) => channel(
  geometry,
  offset,
  [fn(attribute, attribute, 0, physFrom, physTo)],
  def,
);

/** Wheel slot selection: one channel set per slot, evenly spread over 0-255 */
function wheelChannel(geometry, offset, attribute, wheel, slots, extra = []) {
  const step = Math.floor((extra.length ? 128 : 256) / slots.length);
  return channel(geometry, offset, [
    fn(attribute, attribute, 0, 0, 1, { Wheel: wheel }, slots.map((s, i) => ({
      name: s.name, from: i * step, slot: i + 1,
    }))),
    ...extra,
  ]);
}

const shutter = (geometry, offset) => channel(geometry, offset, [
  fn('Closed', 'Shutter1', 0, 0, 0),
  fn('Open', 'Shutter1', 32, 0, 0),
  fn('Strobe', 'Shutter1Strobe', 64, 1, 20),
  fn('Open 2', 'Shutter1', 224, 0, 0),
], 32);

