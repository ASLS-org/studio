function wheelsXML(wheels = []) {
  return el('Wheels', {}, wheels.map((w) => el('Wheel', { Name: w.name }, w.slots.map((s) => el('Slot', {
    Name: s.name,
    Color: s.color || '0.312700,0.329000,100.000000',
    MediaFileName: s.media,
  })))));
}

function description(fixture) {
  const attributes = fixture.modes
    .flatMap((m) => m.channels.flatMap((c) => c.functions.map((f) => f.attribute)));
  return `<?xml version="1.0" encoding="UTF-8" standalone="no"?>\n${el(
    'GDTF',
    { DataVersion: '1.2' },
    el(
      'FixtureType',
      {
        Name: fixture.name,
        ShortName: fixture.shortName,
        LongName: fixture.name,
        Manufacturer: MANUFACTURER,
        Description: 'Generic fixture bundled with ASLS Studio. CC0 1.0 (public domain dedication).',
        FixtureTypeID: fixture.id,
        RefFT: '',
        CanHaveChildren: 'Yes',
        Thumbnail: '',
      },
      attributeDefinitions(attributes),
      wheelsXML(fixture.wheels),
      el('PhysicalDescriptions'),
      el('Models', {}, fixture.models),
      el('Geometries', {}, fixture.geometry),
      el('DMXModes', {}, fixture.modes.map((m) => el(
        'DMXMode',
        { Name: m.name, Geometry: m.root },
        el('DMXChannels', {}, m.channels.map(channelXML)),
        el('Relations'),
        el('FTMacros'),
      ))),
      el('Revisions', {}, el('Revision', {
        Text: REVISION, Date: DATE, UserID: 0, ModifiedBy: 'ASLS Studio',
      })),
      el('FTPresets'),
      el('Protocols'),
    ),
  )()}\n`;
}

function gdtfFile(fixture) {
  const entries = { 'description.xml': [Buffer.from(description(fixture)), { mtime: MTIME }] };
  (fixture.wheels || []).forEach((w) => w.slots.forEach((s) => {
    if (s.media) {
      entries[`wheels/${s.media}.png`] = [greyPNG(rasterizeGobo(s.pattern, IMAGE_SIZE), IMAGE_SIZE), { mtime: MTIME }];
    }
  }));
  return zipSync(entries, { level: 9, mtime: MTIME });
}

